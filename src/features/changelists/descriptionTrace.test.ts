import { expect, it } from "vitest";
import type { ChangelistSummary } from "../../shared/contracts";
import {
  ciSourceReferences,
  reachableDestinations,
  ciDescriptionBody,
  matchesDescriptionDestination,
} from "./descriptionTrace";
const body =
  "[CODE][FIX] Keep body labels\nSecond line --> Task [mock:issue:123]";
const source = { id: 100, description: body };
function row(
  id: number,
  description: string,
  client = "mock-workspace",
): ChangelistSummary {
  return {
    id,
    description,
    client,
    user: "mock-user",
    status: "submitted",
    time: "2026-01-01T12:00:00Z",
    fileCount: 0,
    hasShelf: false,
    jobs: [],
    mergeClassification: "unknown",
  };
}
it("matches original body to distinct CI destinations and retains their own clients and raw descriptions", () => {
  const candidates = [101, 102, 103].map((id) =>
    row(
      id,
      `${body}\n提交人: mock-user\n合并来源: mock-origin\nCL号: 100`,
      `mock-workspace-${id}`,
    ),
  );
  const matches = candidates.filter((candidate) =>
    matchesDescriptionDestination(source, candidate),
  );
  expect(matches.map((candidate) => candidate.id)).toEqual([101, 102, 103]);
  expect(matches.map((candidate) => candidate.client)).toEqual([
    "mock-workspace-101",
    "mock-workspace-102",
    "mock-workspace-103",
  ]);
  expect(matches[0].description).toContain("CL号: 100");
  expect(ciDescriptionBody(matches[0].description)).toBe(body);
});
it("normalizes CRLF and outer whitespace but retains tags, internal spacing and unknown suffixes", () => {
  expect(
    matchesDescriptionDestination(
      source,
      row(
        101,
        ` \r\n${body.replaceAll("\n", "\r\n")}\r\n提交人: mock-user\r\n `,
      ),
    ),
  ).toBe(true);
  for (const description of [
    body.replace("[FIX]", ""),
    body.replace("Second line", "Second  line"),
    `${body}\nunknown suffix`,
  ]) {
    expect(
      matchesDescriptionDestination(
        source,
        row(101, `${description}\n提交人: mock-user`),
      ),
    ).toBe(false);
  }
  expect(
    ciDescriptionBody(`${body}\n提交人: mock-user\nunknown suffix`),
  ).toContain("提交人: mock-user");
  expect(ciDescriptionBody(`提交人: quoted body\n${body}`)).toContain(
    "提交人: quoted body",
  );
});
it("excludes the source, ordinary and autogenerated submissions, pending rows and empty bodies", () => {
  expect(
    matchesDescriptionDestination(
      source,
      row(100, `${body}\n提交人: mock-user`),
    ),
  ).toBe(false);
  expect(matchesDescriptionDestination(source, row(101, body))).toBe(false);
  expect(
    matchesDescriptionDestination(
      source,
      row(101, `[AutoGen]\n${body}\n提交人: mock-user`),
    ),
  ).toBe(false);
  expect(
    matchesDescriptionDestination(source, {
      ...row(101, `${body}\n提交人: mock-user`),
      status: "pending",
    }),
  ).toBe(false);
  expect(
    matchesDescriptionDestination(
      { id: 100, description: "" },
      row(101, "提交人: mock-user"),
    ),
  ).toBe(false);
});

it("traverses exact CI source references across unordered pages, cycles and duplicate paths", () => {
  const linked = (id: number, parent: number, path = "//synthetic/main") =>
    row(id, `different body ${id}\n合并来源: ${path}\nCL号: ${parent}`);
  const child = linked(103, 102);
  expect(reachableDestinations(100, [child])).toEqual([]);
  const parent = linked(102, 100);
  const duplicatePath = row(
    104,
    `${linked(104, 102).description}\n合并来源: //synthetic/second\nCL号: 103`,
  );
  const rows = [
    child,
    parent,
    child,
    duplicatePath,
    linked(100, 104),
    linked(105, 1000),
  ];
  expect(reachableDestinations(100, rows).map((item) => item.id)).toEqual([
    103, 102, 104,
  ]);
  expect(ciSourceReferences(parent.description)).toEqual([
    { changeId: 100, sourcePath: "//synthetic/main" },
  ]);
});
it("rejects unstructured numbers, incomplete pairs, unsafe IDs and malformed metadata", () => {
  for (const description of [
    "issue 100",
    "CL号: 100",
    "合并来源: //synthetic/main",
    "合并来源: //synthetic/main\nCL号: 100junk",
    "合并来源: //synthetic/main\nCL号: 100 101",
    "合并来源: //synthetic/main\nCL号: 9007199254740992",
    "合并来源: not-a-depot-path\nCL号: 100",
    "[AutoGen]\n合并来源: //synthetic/main\nCL号: 100",
  ])
    expect(ciSourceReferences(description)).toEqual([]);
});
