export function menuLabel(label: string, zh: boolean): string {
  if (zh) return label;
  const key = labelKeys[label];
  if (key) return tFor("en-US", key as MsgKey);
  if (label.includes(" › "))
    return label
      .split(" › ")
      .map((value) => menuLabel(value, false))
      .join(" › ");
  if (label.endsWith("…")) return menuLabel(label.slice(0, -1), false) + "…";
  if (/（(含)?递归）$/.test(label))
    return (
      menuLabel(label.replace(/（(含)?递归）$/, ""), false) + " (recursive)"
    );
  if (label.startsWith("复制"))
    return "Copy " + menuLabel(label.slice(2).trim(), false).toLowerCase();
  return label;
}
