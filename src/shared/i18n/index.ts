export function initialLocale(): Locale {
  const saved = storage.getItem("p4deck.locale");
  if (saved === "zh-CN" || saved === "en-US") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}
