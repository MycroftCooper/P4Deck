import { expect, it, vi } from "vitest";
import type {
  ChangelistSummary,
  ClQueryResult,
} from "../../shared/contracts/types";
import {
  classifySubmission,
  collectReport,
  reportBounds,
  reportPrompt,
  reportRange,
  type ReportScope,
} from "./submittedReport";
const scope: ReportScope = {
  user: "alice",
  from: "2026-10-19T00:00",
  to: "2026-10-26T00:00",
  timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone,
};
const row = (
  id: number,
  description = "[CODE] Work",
  time = new Date("2026-10-21T12:00").toISOString(),
): ChangelistSummary => ({
  id,
  description,
  time,
  user: "alice",
  client: "alice_Video_v2d1_main",
  status: "submitted",
  fileCount: 1,
  hasShelf: false,
  jobs: [],
  mergeClassification: "unknown",
});
const page = (
  items: ChangelistSummary[],
  extra: Partial<ClQueryResult> = {},
): ClQueryResult => ({
  requestGeneration: 7,
  items,
  hasMore: false,
  stats: {
    scannedCount: items.length,
    matchedCount: items.length,
    hiddenReliableMergeCount: 0,
    truncatedBySafetyLimit: false,
  },
  ...extra,
});
const options = () => ({
  operationId: "pure-test",
  generation: 7,
  cancelled: () => false,
});
it("uses only exact automation signatures, never a generic merge word or integration proof", () => {
  expect(classifySubmission("Manually merge branch").kind).toBe("ordinary");
  expect(classifySubmission("[AutoGen]\n提交人: alice").kind).toBe(
    "autoGenerated",
  );
  for (const prefix of ["提交人:", "合并来源:", "CL号:"])
    expect(classifySubmission(`Work\n  ${prefix} value`).kind).toBe("ciMerge");
  expect(classifySubmission("text 提交人: alice").kind).toBe("ordinary");
  expect(classifySubmission("提交人：alice").kind).toBe("ordinary");
  expect(classifySubmission("").kind).toBe("ordinary");
});
it("uses complete Monday-based natural weeks, including year boundaries and Sunday", () => {
  expect(reportRange("lastWeek", new Date(2026, 0, 1, 12))).toEqual({
    from: "2025-12-22T00:00",
    to: "2025-12-29T00:00",
  });
  expect(reportRange("thisWeek", new Date(2026, 9, 25, 12))).toEqual({
    from: "2026-10-19T00:00",
    to: "2026-10-26T00:00",
  });
  expect(reportRange("today", new Date(2026, 9, 25, 12))).toEqual({
    from: "2026-10-25T00:00",
    to: "2026-10-26T00:00",
  });
  expect(() => reportBounds({ ...scope, from: "2026-02-30T00:00" })).toThrow();
  expect(() => reportBounds({ ...scope, user: "alice,bob" })).toThrow();
  expect(() => reportBounds({ ...scope, to: scope.from })).toThrow();
});
it("collects independent pages and enforces exact local start-inclusive/end-exclusive bounds", async () => {
  const fetch = vi
    .fn()
    .mockResolvedValueOnce(
      page([row(1, "start", new Date(scope.from).toISOString()), row(2)], {
        hasMore: true,
        nextCursor: "next",
      }),
    )
    .mockResolvedValueOnce(
      page([row(2), row(3, "end", new Date(scope.to).toISOString()), row(4)]),
    );
  const result = await collectReport(scope, fetch, options());
  expect(result.complete).toBe(true);
  expect(result.rows.map((r) => r.id)).toEqual([1, 2, 4]);
  expect(fetch.mock.calls[0][0]).toMatchObject({
    users: ["alice"],
    clients: [],
    keyword: "",
    mergeClassifications: [],
    hideReliableMerges: false,
  });
  expect(fetch.mock.calls[0][0]).not.toHaveProperty("jobs");
  expect(Date.parse(fetch.mock.calls[0][0].from)).toBeLessThan(
    new Date(scope.from).getTime(),
  );
  expect(fetch.mock.calls[1][0].cursor).toBe("next");
});
it("never claims completeness after errors, scan/page/row limits, cancellation or stalled cursors", async () => {
  const first = page([row(1)], { hasMore: true, nextCursor: "same" });
  const error = await collectReport(
    scope,
    vi.fn().mockResolvedValueOnce(first).mockRejectedValue(new Error("denied")),
    options(),
  );
  expect(error.complete).toBe(false);
  expect(error.rows).toHaveLength(1);
  expect(error.reason).toContain("denied");
  expect(
    (
      await collectReport(scope, async () => first, {
        ...options(),
        maxPages: 1,
      })
    ).complete,
  ).toBe(false);
  expect(
    (
      await collectReport(scope, async () => page([row(1), row(2)]), {
        ...options(),
        maxRows: 1,
      })
    ).complete,
  ).toBe(false);
  expect(
    (await collectReport(scope, async () => first, options())).reason,
  ).toContain("cursor");
  const truncated = page([row(1)]);
  truncated.stats.truncatedBySafetyLimit = true;
  expect(
    (await collectReport(scope, async () => truncated, options())).complete,
  ).toBe(false);
  const fetch = vi.fn();
  expect(
    (await collectReport(scope, fetch, { ...options(), cancelled: () => true }))
      .complete,
  ).toBe(false);
  expect(fetch).not.toHaveBeenCalled();
});
it("preserves CLs, full multiline descriptions, task markers and tags without deduplicating equal descriptions", () => {
  const description =
    "[CODE][DOC] Add feature\nFull second line\n--> Task title [rm42:story:123]";
  const result = {
    rows: [
      row(2, description),
      row(1, description),
      row(3, "提交人: bot"),
      row(4, "[AutoGen] generated"),
    ],
    complete: true,
    reason: "",
    pages: 2,
    scanned: 4,
  };
  const prompt = reportPrompt(scope, result, ["ordinary"], true);
  expect(prompt).toContain("[rm42:story:123]");
  expect(prompt).toContain("【v2d1】");
  expect(prompt).toContain("CL 1");
  expect(prompt).toContain("CL 2");
  expect(prompt).not.toContain("CL 3");
  expect(prompt.match(/Full second line/g)).toHaveLength(2);
  expect(prompt).not.toContain("CL 4");
  for (const zh of [true, false]) {
    const output = reportPrompt(scope, result, ["ordinary"], zh);
    expect(output).toContain(
      zh ? "请帮我总结以下工作内容" : "Summarize the following work",
    );
    for (const removed of [
      "用户:",
      "User:",
      "本机时区:",
      "Local timezone:",
      "区间（",
      "Interval (",
      "UTC 边界",
      "UTC bounds",
      "数据状态",
      "Data status",
      "已收集/导出/排除",
      "Collected/exported/excluded",
      "页数/扫描数",
      "Pages/scanned",
      "4/2/2",
      scope.timeZone,
      "普通提交（未命中规则）:",
      "疑似 CI 合并（规则识别）:",
      "自动生成（规则识别）:",
      "(包含)",
      "(排除)",
      "(included)",
      "(excluded)",
      "分类仅依据",
      "Classification uses",
      "description deduplication",
      "不完整",
      "INCOMPLETE",
    ])
      expect(output).not.toContain(removed);
  }
  expect(
    reportPrompt(
      scope,
      { ...result, complete: false, reason: "cancelled" },
      ["ordinary"],
      false,
    ),
  ).toContain("INCOMPLETE");
  expect(
    reportPrompt(
      scope,
      { ...result, rows: [{ ...row(1, ""), client: "no-version" }] },
      ["ordinary"],
      true,
    ),
  ).not.toContain("【v");
});
